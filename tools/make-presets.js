// Regenerates js/presets.js (from samples/*.json) and js/method.js (from METHOD.md):  node tools/make-presets.js
// (presets are a .js file because fetch() of local JSON does not work from file://)
'use strict';
var fs = require('fs'), path = require('path');
var root = path.join(__dirname, '..');
var sample = JSON.parse(fs.readFileSync(path.join(root, 'samples/sample-project.json'), 'utf8'));
var types = JSON.parse(fs.readFileSync(path.join(root, 'samples/vehicle-types.json'), 'utf8'));
fs.writeFileSync(path.join(root, 'js/presets.js'), '/* GENERATED by tools/make-presets.js from samples/*.json - do not edit by hand.\n' +
  ' * FICTIONAL demo data (6-car metro, envelopes and a 4.4 km line); not a real vehicle, customer or line. */\n' +
  '(function (root) {\n  \'use strict\';\n  root.RSGAUGE = root.RSGAUGE || {};\n  root.RSGAUGE.presets = ' +
  JSON.stringify({ sample: sample, vehicleTypes: types }, null, 2).replace(/\n/g, '\n  ') + ';\n}(typeof globalThis !== \'undefined\' ? globalThis : this));\n');
console.log('wrote js/presets.js');
var method = fs.readFileSync(path.join(root, 'METHOD.md'), 'utf8');
fs.writeFileSync(path.join(root, 'js/method.js'), '/* GENERATED by tools/make-presets.js from METHOD.md - do not edit by hand. */\n' +
  '(function (root) {\n  \'use strict\';\n  root.RSGAUGE = root.RSGAUGE || {};\n  root.RSGAUGE.methodMd = ' + JSON.stringify(method) + ';\n}(typeof globalThis !== \'undefined\' ? globalThis : this));\n');
console.log('wrote js/method.js');
